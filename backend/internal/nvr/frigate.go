// IntelGPU reports an Intel graphics render node (VA-API decoding, OpenVINO).
func IntelGPU() string {
	nodes, _ := filepath.Glob("/sys/class/drm/renderD*")
	sort.Strings(nodes)
	for _, n := range nodes {
		v, err := os.ReadFile(filepath.Join(n, "device", "vendor"))
		if err == nil && strings.TrimSpace(string(v)) == "0x8086" {
			return "/dev/dri/" + filepath.Base(n)
		}
	}
	return ""
}

// CoralUSB reports a Coral USB accelerator (before and after its firmware loads).
func CoralUSB() bool {
	ids, _ := filepath.Glob("/sys/bus/usb/devices/*/idVendor")
	for _, p := range ids {
		v, _ := os.ReadFile(p)
		prod, _ := os.ReadFile(filepath.Join(filepath.Dir(p), "idProduct"))
		vp := strings.TrimSpace(string(v)) + ":" + strings.TrimSpace(string(prod))
		if vp == "1a6e:089a" || vp == "18d1:9302" {
			return true
		}
	}
	return false
}

// ResolveDetector picks the detector for "auto": Coral, else Intel GPU, else CPU.
func ResolveDetector(choice, gpu string, coral bool) string {
	switch choice {
	case "cpu", "openvino", "edgetpu":
		return choice
	}
	if coral {
		return "edgetpu"
	}
	if gpu != "" {
		return "openvino"
	}
	return "cpu"
}


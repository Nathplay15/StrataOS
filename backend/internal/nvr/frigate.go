// FrigateEvent is an event of Frigate's API (/api/events).
type FrigateEvent struct {
	ID        string  `json:"id"`
	Camera    string  `json:"camera"`
	Label     string  `json:"label"`
	StartTime float64 `json:"start_time"`
	TopScore  float64 `json:"top_score"`
	Data      struct {
		TopScore float64 `json:"top_score"`
	} `json:"data"`
}

// Score of the event (0..1), wherever this version of Frigate puts it.
func (e FrigateEvent) Score() float64 { return max(e.TopScore, e.Data.TopScore) }

// EventFilter keeps the polling state: it returns each event once and limits
// the notifications to one per camera per period.
type EventFilter struct {
	Cursor   float64 // events starting before it are old
	seen     map[string]float64
	notified map[string]time.Time
}

// eventOverlap: events are polled again this far back (they are listed when
// they start, sometimes late).
const eventOverlap = 300

func NewEventFilter(now time.Time) *EventFilter {
	return &EventFilter{Cursor: float64(now.Unix()), seen: map[string]float64{}, notified: map[string]time.Time{}}
}

// After is the "after" parameter of the next poll.
func (f *EventFilter) After() float64 { return f.Cursor - eventOverlap }

// New returns the events not seen yet, oldest first, and moves the cursor.
func (f *EventFilter) New(events []FrigateEvent) []FrigateEvent {
	out := []FrigateEvent{}
	for _, e := range events {
		if e.ID == "" || e.StartTime < f.After() {
			continue
		}
		if _, ok := f.seen[e.ID]; ok {
			continue
		}
		f.seen[e.ID] = e.StartTime
		out = append(out, e)
		if e.StartTime > f.Cursor {
			f.Cursor = e.StartTime
		}
	}
	// Forget what can no longer be listed.
	for id, t := range f.seen {
		if t < f.After() {
			delete(f.seen, id)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].StartTime < out[j].StartTime })
	return out
}

// ShouldNotify reports whether an event of camera may be notified now.
func (f *EventFilter) ShouldNotify(camera string, now time.Time, every time.Duration) bool {
	if last, ok := f.notified[camera]; ok && now.Sub(last) < every {
		return false
	}
	f.notified[camera] = now
	return true
}

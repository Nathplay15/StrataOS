// Frigate (App Center app "frigate") records the cameras given to it, with
// object detection. StrataOS writes its config.yml from the cameras of the
// Surveillance app; the credentials go to secret files that Frigate reads
// from /run/secrets and substitutes into {FRIGATE_…} placeholders, so the
// configuration (shown in Frigate's editor and in StrataOS) holds none.

// FrigateSecretsDir is mounted read-only at /run/secrets in the container.
var FrigateSecretsDir = "/var/lib/strata/nvr/frigate-secrets"

// Objects Frigate's default models detect that the interface offers.
var FrigateObjects = []string{"person", "car", "bicycle", "motorcycle", "bus", "truck", "dog", "cat", "bird", "horse"}

// FrigateCamera is a camera handed to Frigate.
type FrigateCamera struct {
	Name     string // Frigate camera name (see FrigateNames)
	Main     string // clean stream URLs (no credentials)
	Sub      string
	User     string
	Pass     string
	KeepDays int // continuous recording; 0 = as long as space allows
}

// FrigateOptions is everything config.yml is generated from.
type FrigateOptions struct {
	Detector string // cpu | openvino | edgetpu
	Objects  []string
	Cameras  []FrigateCamera
}

var slugRe = regexp.MustCompile(`[^a-z0-9]+`)

// FrigateNames gives each camera (by ID, in order) a Frigate name: the camera
// name in lower case with underscores, unique (Frigate accepts [a-zA-Z0-9_-]).
func FrigateNames(ids, names []string) map[string]string {
	out := map[string]string{}
	taken := map[string]bool{}
	for i, id := range ids {
		base := strings.Trim(slugRe.ReplaceAllString(strings.ToLower(names[i]), "_"), "_")
		if base == "" || base[0] >= '0' && base[0] <= '9' {
			base = "cam_" + base
		}
		base = strings.TrimSuffix(base, "_")
		if len(base) > 40 {
			base = base[:40]
		}
		n := base
		for k := 2; taken[n]; k++ {
			n = base + "_" + strconv.Itoa(k)
		}
		taken[n] = true
		out[id] = n
	}
	return out
}

// secretVar is the name of the secret holding a camera's user or password.
func secretVar(cam, what string) string {
	return "FRIGATE_" + strings.ToUpper(strings.ReplaceAll(cam, "-", "_")) + "_" + what
}

// frigateURL is a stream URL with {FRIGATE_…} placeholders for the credentials.
func frigateURL(c FrigateCamera, clean string) string {
	info := userinfo("{"+secretVar(c.Name, "USER")+"}", "{"+secretVar(c.Name, "PASS")+"}", c.User != "", c.Pass != "")
	return withUserinfo(clean, info)
}

// FrigateSecrets maps secret file names to their content (escaped credentials).
func FrigateSecrets(o FrigateOptions) map[string]string {
	out := map[string]string{}
	for _, c := range o.Cameras {
		if c.User != "" {
			out[secretVar(c.Name, "USER")] = Escape(c.User)
		}
		if c.Pass != "" {
			out[secretVar(c.Name, "PASS")] = Escape(c.Pass)
		}
	}
	return out
}

// q quotes a YAML scalar (inputs are validated: printable ASCII only).
func q(s string) string { return strconv.Quote(s) }

// unlimitedDays: Frigate needs a number; it deletes the oldest recordings
// itself when the disk is nearly full.
const unlimitedDays = 3650

// FrigateConfig generates config.yml.
func FrigateConfig(o FrigateOptions) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Generated by StrataOS from the cameras of the Surveillance app.")
	w("# Changes made here are overwritten: edit the cameras in StrataOS.")
	w("mqtt:")
	w("  enabled: false")
	w("detectors:")
	switch o.Detector {
	case "openvino":
		w("  ov:")
		w("    type: openvino")
		w("    device: GPU")
		w("model:")
		w("  width: 300")
		w("  height: 300")
		w("  input_tensor: nhwc")
		w("  input_pixel_format: bgr")
		w("  path: /openvino-model/ssdlite_mobilenet_v2.xml")
		w("  labelmap_path: /openvino-model/coco_91cl_bkgr.txt")
	case "edgetpu":
		w("  coral:")
		w("    type: edgetpu")
		w("    device: usb")
	default:
		w("  cpu1:")
		w("    type: cpu")
		w("    num_threads: 2")
	}
	objects := o.Objects
	if len(objects) == 0 {
		objects = []string{"person"}
	}
	w("objects:")
	w("  track:")
	for _, obj := range objects {
		w("    - %s", q(obj))
	}
	w("record:")
	w("  enabled: true")
	w("snapshots:")
	w("  enabled: true")
	w("  retain:")
	w("    default: 10")
	if len(o.Cameras) == 0 {
		w("cameras: {}")
		return b.String()
	}
	w("cameras:")
	for _, c := range o.Cameras {
		days := c.KeepDays
		if days <= 0 {
			days = unlimitedDays
		}
		w("  %s:", c.Name)
		w("    enabled: true")
		w("    ffmpeg:")
		w("      inputs:")
		if c.Sub != "" {
			w("        - path: %s", q(frigateURL(c, c.Main)))
			w("          roles:")
			w("            - record")
			w("        - path: %s", q(frigateURL(c, c.Sub)))
			w("          roles:")
			w("            - detect")
		} else {
			w("        - path: %s", q(frigateURL(c, c.Main)))
			w("          roles:")
			w("            - detect")
			w("            - record")
		}
		w("    detect:")
		w("      enabled: true")
		w("    record:")
		w("      enabled: true")
		w("      continuous:")
		w("        days: %d", days)
	}
	return b.String()
}


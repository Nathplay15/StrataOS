#!/bin/bash
# Builds the macOS parts of files on demand (macOS only, Xcode's swiftc):
#   desktop/macos/build.sh OUT
# OUT/PlugIns/StrataOSFileProvider.appex   File Provider extension (the NAS in Finder)
# OUT/PlugIns/StrataOSFinderSync.appex     Finder Sync extension (share link, open on the NAS)
# OUT/MacOS/strataos-fileprovider          helper the agent runs (domains, signals, agent.json)
# Universal (arm64 + x86_64), macOS 11+. desktop/packaging/build.sh puts them
# in the app with Tauri's bundle.macOS.files and signs the app after them.
#
# Signing: APPLE_SIGNING_IDENTITY ("Developer ID Application: … (TEAMID)") and
# APPLE_TEAM_ID sign them for other Macs (hardened runtime, timestamp; the app
# group is TEAMID.io.github.nathplay15.strataos). Without them they are signed
# ad hoc with the group "group.io.github.nathplay15.strataos": that builds and
# checks the code, but macOS only runs File Provider extensions of a signed
# app (see docs/DEVELOPMENT.md).
set -euo pipefail
cd "$(dirname "$0")"
SRC=$PWD
OUT=${1:?usage: build.sh OUT}
mkdir -p "$OUT"
OUT=$(cd "$OUT" && pwd)
V=$(cat ../../VERSION)
V=${V%%~*}
APP_ID=io.github.nathplay15.strataos.desktop
IDENTITY=${APPLE_SIGNING_IDENTITY:--}
if [ -n "${APPLE_TEAM_ID:-}" ]; then
  GROUP="$APPLE_TEAM_ID.io.github.nathplay15.strataos"
else
  GROUP="group.io.github.nathplay15.strataos"
fi
W="$OUT/.work"
rm -rf "$W" "$OUT/PlugIns" "$OUT/MacOS"
mkdir -p "$W" "$OUT/PlugIns" "$OUT/MacOS"

cat > "$W/BuildConfig.swift" <<EOF
// Generated by desktop/macos/build.sh.
enum BuildConfig {
    static let appGroup = "$GROUP"
    static let appID = "$APP_ID"
}
EOF
CORE=("$SRC"/Sources/StrataOSCore/*.swift "$W/BuildConfig.swift")

# compile NAME OUTFILE [swiftc arguments…]: both architectures, then lipo.
compile() {
  local name=$1 out=$2 a
  shift 2
  for a in arm64 x86_64; do
    xcrun swiftc -target "$a-apple-macos11.0" -O -swift-version 5 -module-name "$name" \
      -o "$W/$name.$a" "$@"
  done
  lipo -create -output "$out" "$W/$name.arm64" "$W/$name.x86_64"
}

entitlements() { # FILE SANDBOX(true|false)
  cat > "$1" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
$( [ "$2" = true ] && printf '<key>com.apple.security.app-sandbox</key><true/>\n<key>com.apple.security.network.client</key><true/>' )
<key>com.apple.security.application-groups</key><array><string>$GROUP</string></array>
</dict></plist>
EOF
}

sign() { # PATH ENTITLEMENTS
  if [ "$IDENTITY" = - ]; then
    codesign --force --sign - --entitlements "$2" "$1"
  else
    codesign --force --sign "$IDENTITY" --options runtime --timestamp --entitlements "$2" "$1"
  fi
}

appex() { # NAME PRINCIPAL POINT EXTRA_PLIST SOURCES… -- FRAMEWORKS…
  local name=$1 principal=$2 point=$3 extra=$4
  shift 4
  local b="$OUT/PlugIns/$name.appex/Contents"
  mkdir -p "$b/MacOS" "$b/Resources"
  compile "$name" "$b/MacOS/$name" -parse-as-library -application-extension \
    -Xlinker -e -Xlinker _NSExtensionMain "$@"
  cat > "$b/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleIdentifier</key><string>$APP_ID.$(echo "$name" | tr '[:upper:]' '[:lower:]')</string>
<key>CFBundleExecutable</key><string>$name</string>
<key>CFBundleName</key><string>$name</string>
<key>CFBundleDisplayName</key><string>StrataOS</string>
<key>CFBundlePackageType</key><string>XPC!</string>
<key>CFBundleShortVersionString</key><string>$V</string>
<key>CFBundleVersion</key><string>$V</string>
<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
<key>CFBundleDevelopmentRegion</key><string>en</string>
<key>LSMinimumSystemVersion</key><string>11.0</string>
<key>NSExtension</key><dict>
<key>NSExtensionPointIdentifier</key><string>$point</string>
<key>NSExtensionPrincipalClass</key><string>$principal</string>
$extra
</dict>
</dict></plist>
EOF
}

appex StrataOSFileProvider StrataOSFileProviderExtension com.apple.fileprovider-nonui \
  "<key>NSExtensionFileProviderDocumentGroup</key><string>$GROUP</string><key>NSExtensionFileProviderSupportsEnumeration</key><true/>" \
  "${CORE[@]}" "$SRC"/FileProvider/*.swift -framework FileProvider -framework UniformTypeIdentifiers
appex StrataOSFinderSync StrataOSFinderSync com.apple.FinderSync \
  "<key>NSExtensionAttributes</key><dict/>" \
  "${CORE[@]}" "$SRC"/FinderSync/*.swift -framework FinderSync -framework Cocoa
cp -R "$SRC"/FinderSync/*.lproj "$OUT/PlugIns/StrataOSFinderSync.appex/Contents/Resources/"

compile strataos_fileprovider "$OUT/MacOS/strataos-fileprovider" "${CORE[@]}" "$SRC"/Helper/main.swift -framework FileProvider

entitlements "$W/extension.entitlements" true
entitlements "$W/helper.entitlements" false
sign "$OUT/PlugIns/StrataOSFileProvider.appex" "$W/extension.entitlements"
sign "$OUT/PlugIns/StrataOSFinderSync.appex" "$W/extension.entitlements"
sign "$OUT/MacOS/strataos-fileprovider" "$W/helper.entitlements"
codesign --verify --strict "$OUT/PlugIns/StrataOSFileProvider.appex" "$OUT/PlugIns/StrataOSFinderSync.appex" "$OUT/MacOS/strataos-fileprovider"
rm -rf "$W"
echo "$OUT (app group $GROUP, signed by $IDENTITY)"

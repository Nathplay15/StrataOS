export const tagLabel = (t: string) => PHOTO_TAGS[t] ?? t;

/** The tag a search names, in the interface language or in English. */
export function tagOf(q: string): string | undefined {
  const s = q.trim().toLowerCase();
  return Object.keys(PHOTO_TAGS).find((t) => t === s || PHOTO_TAGS[t].toLowerCase() === s);
}

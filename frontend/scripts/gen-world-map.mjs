// Writes src/lib/worldMap.ts from Natural Earth's 1:110m land polygons
// (public domain, https://www.naturalearthdata.com/), as one SVG path in an
// equirectangular projection: x = longitude + 180, y = 90 - latitude.
// Usage: node scripts/gen-world-map.mjs ne_110m_land.geojson
import { readFileSync, writeFileSync } from "node:fs";

const geo = JSON.parse(readFileSync(process.argv[2], "utf8"));
const r = (v) => Math.round(v * 10) / 10;
let d = "";
for (const f of geo.features) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      let last = "";
      ring.forEach(([lon, lat], i) => {
        const pt = `${r(lon + 180)} ${r(90 - lat)}`;
        if (pt === last) return;
        d += (i === 0 ? "M" : "L") + pt;
        last = pt;
      });
      d += "Z";
    }
  }
}
writeFileSync(new URL("../src/lib/worldMap.ts", import.meta.url), `// Generated by scripts/gen-world-map.mjs from Natural Earth (public domain).\n// Land of the world, equirectangular: x = longitude + 180, y = 90 - latitude.\nexport const LAND = "${d}";\n`);
console.log(d.length, "characters");
